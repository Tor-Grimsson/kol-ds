/* a pixel glyph as one ring per lit run of cells along each row (fewer, wider rings than per cell) */
export function pixelRings(ch) {
  const g = PX[ch] ?? PX[ch?.toUpperCase?.()] ?? PX[ch?.toLowerCase?.()]
  if (!g) return []
  const rings = []
  g.forEach((row, j) => {
    let i = 0
    while (i < 5) {
      if (row[i] !== '#') { i++; continue }
      let e = i
      while (e < 5 && row[e] === '#') e++
      const x0 = i / 5, x1 = e / 5, y0 = j / 7, y1 = (j + 1) / 7
      rings.push([[x0, y0], [x1, y0], [x1, y1], [x0, y1]])
      i = e
    }
  })
  return rings
}
