export const PARATYPE_DEFAULTS = Object.fromEntries(glyphDef.params.map((q) => [q.key, q.default]))
export const PARATYPE_GLYPHS = ['o', 'l', 'i', 'd', 'b', 'p', 'q', 'c', 'e', 'n', 'h', 'm', 't']

/* a Paratype glyph as rings in a 0..1 em box (y down, baseline-to-cap fitted): `params` overrides the
   engine's defaults (stem, contrast …). The em is ascender + descender tall, the glyph sits on its
   baseline, so letters of one set line up. */
export function paratypeRings(name, params = {}, engine = 'classic') {
  const p = { ...PARATYPE_DEFAULTS, ...params }
  const g = renderGlyph(engine, name, p)
  if (!g) return []
  const top = p.ascender, em = p.ascender + p.descender
  const rings = []
  for (const path of g.paths) for (const r of flattenD(path.d, 6)) rings.push(r)
  const w = Math.max(g.width, 1)
  /* font units are y-up from the baseline; the em box is y-down from the ascender line */
  return rings.map((r) => r.map(([x, y]) => [(x + (em - w) / 2) / em, (top - y) / em]))
}
